# ── 採集器設定 ──────────────────────────────────────────────────────────
def _trash2_exclude():
    """沿用上一輪的排除清單, 只調整與「店铺装潢」有關的幾個字"""
    from trash_rules import _trash_exclude as _base
    ex = list(_base())
    # 「公共场所」在這一輪可能是店鋪/公共空間的裝飾桶 → 放寬, 交給複審的 ctx 處理
    for w in ("公共场所",):
        if w in ex:
            ex.remove(w)
    # 「桶模型/玩具」: 店鋪裝飾也可能有造型公仔款 → 放寬造型, 只擋純玩具
    for w in ("桶模型", "公仔"):
        if w in ex:
            ex.remove(w)
    return ex


