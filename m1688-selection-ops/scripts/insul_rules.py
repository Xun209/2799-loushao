"""insul_rules.py — 保溫飯盒 / 保溫湯罐 / 保溫箱 品類的複審規則

品類範圍 (2026-10-20 使用者指定):
  * 保温飯盒 / 便當盒 / 餐盒 / 分格飯盒
  * 保温湯罐 / 提鍋 / 焖燒罐 / 保温桶
  * 保温箱 / 冷藏箱 / 保鮮箱 / 釣魚箱 (戶外保生鮮、冰塊)

條件: 售價 20-220、銷量 200+、排除國際與國內大品牌

結構 (與 cup_rules.py 一致, 判定順序由 v3_rules.py 統一):
  brand_rules  品牌 / 仿牌 / IP
  keep_rules   保護清單: 命中就整條放行
  must_words   正面條件: 標題不含本類關鍵字就刪
  nonfit_rules 非本類: 一次性外賣 / 食物 / 服飾 / 家具 / 電器 / 醫療 …

設計重點:
  * 「XX套装」是本類最常見寫法, 所有「包/袋/套/盒」類規則加 (?!装) 負向斷言
  * 焖燒罐/焖燒壺/焖燒鍋是保溫湯罐類 (不是「燉菜電器」), 要保護
  * 「保鮮箱/生鮮箱/水果箱/泡沫保溫箱」是本類正品, 不能被食物規則連帶殺掉
  * 鍋具 (湯鍋/炒鍋/火鍋) 與非食物桶 (油桶/米桶/泡腳桶) 要用 (?<!保温) 負向斷言,
    否則「保温湯鍋」「保温桶」會被誤殺, 而純鍋具會被誤留
"""


def _g(label, words, guard=False):
    """把字串清單轉成 nonfit 規則; guard=True 會加 (?!装) 防「套装」誤判"""
    if guard:
        return [(w + "(?!装)", label) for w in words]
    return [(w, label) for w in words]


