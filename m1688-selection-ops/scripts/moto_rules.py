def _rules(words, label):
    """一般字串 → nonfit 規則"""
    return [(w, label) for w in words]


def _brand_rules(words):
    """品牌 / IP → 品牌規則 (回傳名稱就是字串本身)"""
    return [(f"(?i){re_escape(w)}", w) for w in words]


import re as _re


def re_escape(s):
    return _re.escape(s)


