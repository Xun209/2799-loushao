def _must(box_words):
    """正面下限: 同時命中「箱型字」與「車輛語境字」才保留"""
    b = "|".join(box_words)
    v = "|".join(_VEHICLE_CONTEXT)
    return f"(?=.*({b}))(?=.*({v}))"


def _brand_ctx_keep(box_words):
    """車廠專屬改裝件豁免規則 (2026-10-30 使用者決定)

    命中 = 標題裡的車廠名只是「適配哪台車」而不是品牌 → 整組跳過 brand_ctx_rules。
    三個條件: 車廠名 + 本類品項字 + 機車語境 (說明見 _MOTO_CARRIER 上方)。
    """
    brands = "|".join(re_escape(w) for w in VEHICLE_BRANDS)
    boxes = "|".join(box_words)
    pat = rf"(?i)(?=.*(?:{brands}))(?=.*(?:{boxes}))(?=.*(?:{_MOTO_CARRIER}))"
    return [(pat, "車廠專屬改裝件")]


