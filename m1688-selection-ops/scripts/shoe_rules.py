"""shoe_rules.py — 舞蹈鞋 / 攀岩鞋 / 溯溪鞋 品類的複審規則

品類範圍 (2026-10-28 使用者指定):
  * DANCE  舞蹈鞋 (爵士/拉丁/國標/摩登/街舞/芭蕾/練功/體操)  價 10-200, 銷量 100+
  * CLIMB  攀岩鞋 (室內/戶外/抱石/飛檐/拖鞋)                價 10-200, 銷量 100+
  * WATER  溯溪鞋 (溯溪/涉水/抓地/水鞋)                       價 10-200, 銷量 100+

設計重點 (踩過的坑):
  * 「鞋」是全站最大的非本類污染源: 鞋墊/鞋帶/鞋盒/襪子/其他鞋種 一定要擋
    → 採集階段敏感詞就擋掉, 複審階段再用 must_words 兜底
  * must_words 用「舞鞋/攀岩/溯溪」這種品類專屬詞, 不要用「鞋」當通稱
    (「鞋」會讓跑鞋/球鞋/雨鞋全部混進來)
  * 「戶外運動鞋 / 登山鞋 / 徒步鞋」是溯溪鞋與攀岩鞋的**行銷說法**,
    寫在標題裡是本類正品 → 不能擋
  * 「溯溪」和「攀岩」在 1688 大量重疊 (同一雙鞋兩種搜尋都會出來)
    → 溯溪優先: 標題同時有溯溪+攀岩的歸 WATER 清單, CLIMB 清單排除
  * 鞋的品牌沒有「相容性豁免」: 標題出現品牌就是要刪 (使用者要求「不要知名品牌」)
  * 兒童/少兒版本不擋 (「少儿舞蹈鞋」是本類正品, must_words 會擋掉其他兒童鞋)

結構 (與 cup_rules.py / insul_rules.py / moto_rules.py 一致, 判定由 v3_rules.py 統一):
  brand_rules     品牌 / IP, 一律刪
  must_words      正面條件: 標題不含本類關鍵字就刪
  nonfit_rules    非本類: 鞋類配件 / 其他鞋種 / 服飾 / 儀器 …
"""


def _rules(words, label):
    return [(w, label) for w in words]


def _brand_rules(words):
    return [(f"(?i){_re.escape(w)}", w) for w in words]


