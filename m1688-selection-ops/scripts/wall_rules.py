def _mk_brand_rules(words):
    """英文 4 字母以上用 (?i) 不分大小寫; 其餘用字面比對 (避免 '3M' 誤中 '3mm')"""
    out = []
    for w in words:
        if re.fullmatch(r"[A-Za-z]{4,}", w):
            out.append((f"(?i){re.escape(w)}", w))
        else:
            out.append((re.escape(w), w))
    return out


